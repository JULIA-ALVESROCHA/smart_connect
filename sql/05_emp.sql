CREATE TABLE emp.empresa (
  id_empresa      integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cnpj            ref.cnpj     NOT NULL UNIQUE,
  razao_social    varchar(150) NOT NULL,
  nome_fantasia   varchar(100),
  cod_cnae_classe char(5)      NOT NULL REFERENCES ref.cnae_classe,
  porte           varchar(6)   NOT NULL CHECK (porte IN ('MEI','ME','EPP','MEDIA','GRANDE')),
  id_logradouro   integer      NOT NULL REFERENCES cid.logradouro,
  numero          varchar(10)  NOT NULL,
  email           varchar(254) CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  telefone        varchar(11),
  data_abertura   date         NOT NULL CHECK (data_abertura <= CURRENT_DATE),
  situacao        varchar(10)  NOT NULL DEFAULT 'ATIVA' CHECK (situacao IN ('ATIVA','SUSPENSA','BAIXADA')),
  data_cadastro   timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE emp.empresa IS 'Empresas do municipio (EMP-RF01). Setor economico pela CNAE 2.3 do IBGE';

CREATE TABLE emp.area_profissional (
  id_area smallint    PRIMARY KEY,
  nome    varchar(50) NOT NULL UNIQUE
);
COMMENT ON TABLE emp.area_profissional IS 'Areas do portal de vagas (EMP-RF07: vagas abertas por area)';

-- Ponto em aberto 03 resolvido: estados e transicoes ficam em tabelas, nao no codigo.
CREATE TABLE emp.status_vaga (
  codigo             varchar(10) PRIMARY KEY,
  descricao          varchar(80) NOT NULL,
  aceita_candidatura boolean     NOT NULL
);
CREATE TABLE emp.transicao_vaga (
  de   varchar(10) NOT NULL REFERENCES emp.status_vaga,
  para varchar(10) NOT NULL REFERENCES emp.status_vaga,
  PRIMARY KEY (de, para),
  CHECK (de <> para)
);
CREATE TABLE emp.status_candidatura (
  codigo    varchar(10) PRIMARY KEY,
  descricao varchar(80) NOT NULL,
  ativa     boolean     NOT NULL   -- "candidatura ativa" do glossario: ainda nao encerrada
);
CREATE TABLE emp.transicao_candidatura (
  de   varchar(10) NOT NULL REFERENCES emp.status_candidatura,
  para varchar(10) NOT NULL REFERENCES emp.status_candidatura,
  PRIMARY KEY (de, para),
  CHECK (de <> para)
);

