CREATE TABLE emp.vaga (
  id_vaga                integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa             integer       NOT NULL REFERENCES emp.empresa,           -- EMP-RN01
  id_area                smallint      NOT NULL REFERENCES emp.area_profissional,
  cod_cbo                char(6)       NOT NULL REFERENCES ref.cbo_ocupacao,
  titulo                 varchar(150)  NOT NULL,
  descricao              text,
  tipo_contrato          varchar(10)   NOT NULL CHECK (tipo_contrato IN ('CLT','ESTAGIO','APRENDIZ','TEMPORARIO','PJ')),
  salario                numeric(10,2) CHECK (salario > 0),
  qtd_posicoes           smallint      NOT NULL DEFAULT 1 CHECK (qtd_posicoes > 0),
  id_escolaridade_minima smallint      NOT NULL REFERENCES ref.escolaridade,
  data_publicacao        date          NOT NULL DEFAULT CURRENT_DATE,
  data_encerramento      date,
  status                 varchar(10)   NOT NULL DEFAULT 'ABERTA' REFERENCES emp.status_vaga,
  CONSTRAINT ck_vaga_datas CHECK (data_encerramento IS NULL OR data_encerramento >= data_publicacao),
  CONSTRAINT ck_vaga_encerramento CHECK ((status IN ('ABERTA','SUSPENSA')) = (data_encerramento IS NULL))
);
COMMENT ON TABLE emp.vaga IS 'Vagas de emprego (EMP-RF02). EMP-RN01: id_empresa obrigatorio. Ocupacao pela CBO 2002';

CREATE TABLE emp.candidato (
  id_candidato        integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cidadao          integer       NOT NULL REFERENCES cid.cidadao,
  id_escolaridade     smallint      NOT NULL REFERENCES ref.escolaridade,
  id_area_interesse   smallint      REFERENCES emp.area_profissional,
  pretensao_salarial  numeric(10,2) CHECK (pretensao_salarial > 0),
  resumo_profissional text,
  data_cadastro       date          NOT NULL DEFAULT CURRENT_DATE,
  situacao            varchar(8)    NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO','INATIVO')),
  CONSTRAINT uq_candidato_cidadao UNIQUE (id_cidadao)
);
COMMENT ON TABLE emp.candidato IS 'Papel de candidato de um cidadao (EMP-RF03). Dados pessoais ficam em cid.cidadao';

CREATE TABLE emp.candidatura (
  id_candidatura   integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_candidato     integer     NOT NULL REFERENCES emp.candidato,   -- EMP-RN02
  id_vaga          integer     NOT NULL REFERENCES emp.vaga,        -- EMP-RN02
  data_candidatura timestamptz NOT NULL DEFAULT now(),
  status           varchar(10) NOT NULL DEFAULT 'ENVIADA' REFERENCES emp.status_candidatura,  -- EMP-RN05
  data_status      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_candidatura_datas CHECK (data_status >= data_candidatura)
);
-- EMP-RN03: no maximo uma candidatura ATIVA por candidato e vaga. Depois de recusada ou
-- cancelada, o candidato pode se candidatar de novo. O predicado repete os codigos com ativa = true.
CREATE UNIQUE INDEX uq_candidatura_ativa ON emp.candidatura (id_candidato, id_vaga)
  WHERE status IN ('ENVIADA','EM_ANALISE','ENTREVISTA','APROVADA');
COMMENT ON TABLE emp.candidatura IS 'Candidaturas (EMP-RF04). EMP-RN03 via indice unico parcial uq_candidatura_ativa';

-- EMP-RNF04: historico completo e somente de insercao das mudancas de status.
CREATE TABLE emp.candidatura_historico (
  id_historico    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_candidatura  integer     NOT NULL REFERENCES emp.candidatura,
  status_anterior varchar(10) REFERENCES emp.status_candidatura,
  status_novo     varchar(10) NOT NULL REFERENCES emp.status_candidatura,
  data_hora       timestamptz NOT NULL DEFAULT now(),
  usuario         varchar(63) NOT NULL DEFAULT aud.fn_usuario(),
  observacao      varchar(200)
);
COMMENT ON TABLE emp.candidatura_historico IS 'Linha do tempo de cada candidatura (EMP-UC04 passo 4). Somente insercao';

-- ---------------------------------------------------------------------
-- Gatilhos de candidatura
-- ---------------------------------------------------------------------
CREATE FUNCTION emp.tg_candidatura_bi() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = emp, pg_temp AS $$
DECLARE v_status text;
BEGIN
  -- FOR SHARE: a vaga nao muda de status enquanto esta candidatura e gravada.
  SELECT status INTO v_status FROM emp.vaga WHERE id_vaga = NEW.id_vaga FOR SHARE;
  IF NOT coalesce((SELECT aceita_candidatura FROM emp.status_vaga WHERE codigo = v_status), false) THEN
    RAISE EXCEPTION 'EMP-RN04: a vaga % esta % e nao recebe candidaturas', NEW.id_vaga, coalesce(v_status, 'inexistente')
      USING ERRCODE = 'SC301';
  END IF;
  NEW.status := 'ENVIADA';           -- EMP-RN05: toda candidatura nasce com status definido
  NEW.data_status := NEW.data_candidatura;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_candidatura_bi BEFORE INSERT ON emp.candidatura
  FOR EACH ROW EXECUTE FUNCTION emp.tg_candidatura_bi();

CREATE FUNCTION emp.tg_candidatura_bu() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = emp, pg_temp AS $$
BEGIN
  IF (NEW.id_candidato, NEW.id_vaga, NEW.data_candidatura) IS DISTINCT FROM (OLD.id_candidato, OLD.id_vaga, OLD.data_candidatura) THEN
    RAISE EXCEPTION 'EMP-RN02: candidato, vaga e data de uma candidatura nao podem ser alterados' USING ERRCODE = 'SC302';
  END IF;
  IF NEW.status <> OLD.status THEN
    IF NOT EXISTS (SELECT 1 FROM emp.transicao_candidatura WHERE de = OLD.status AND para = NEW.status) THEN
      RAISE EXCEPTION 'EMP-RN05: transicao de candidatura % -> % nao permitida', OLD.status, NEW.status
        USING ERRCODE = 'SC302';
    END IF;
    NEW.data_status := now();
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_candidatura_bu BEFORE UPDATE ON emp.candidatura
  FOR EACH ROW EXECUTE FUNCTION emp.tg_candidatura_bu();

CREATE FUNCTION emp.tg_candidatura_historico() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = emp, aud, pg_temp AS $$
DECLARE v_contratados integer; v_posicoes integer;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO emp.candidatura_historico (id_candidatura, status_anterior, status_novo, data_hora)
    VALUES (NEW.id_candidatura, NULL, NEW.status, NEW.data_candidatura);
  ELSIF NEW.status <> OLD.status THEN
    INSERT INTO emp.candidatura_historico (id_candidatura, status_anterior, status_novo, data_hora, observacao)
    VALUES (NEW.id_candidatura, OLD.status, NEW.status, NEW.data_status,
            nullif(current_setting('app.observacao', true), ''));
    -- Contratacao que completa as posicoes fecha a vaga automaticamente.
    IF NEW.status = 'CONTRATADA' THEN
      SELECT qtd_posicoes INTO v_posicoes FROM emp.vaga WHERE id_vaga = NEW.id_vaga FOR UPDATE;
      SELECT count(*) INTO v_contratados FROM emp.candidatura WHERE id_vaga = NEW.id_vaga AND status = 'CONTRATADA';
      IF v_contratados >= v_posicoes THEN
        UPDATE emp.vaga SET status = 'PREENCHIDA' WHERE id_vaga = NEW.id_vaga AND status = 'ABERTA';
      END IF;
    END IF;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER tg_candidatura_aiu AFTER INSERT OR UPDATE OF status ON emp.candidatura
  FOR EACH ROW EXECUTE FUNCTION emp.tg_candidatura_historico();

-- Historico somente de insercao.
CREATE FUNCTION emp.tg_historico_imutavel() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'EMP-RNF04: o historico de candidaturas nao pode ser alterado nem apagado' USING ERRCODE = 'SC303';
END $$;
CREATE TRIGGER tg_candidatura_historico_bud BEFORE UPDATE OR DELETE ON emp.candidatura_historico
  FOR EACH ROW EXECUTE FUNCTION emp.tg_historico_imutavel();

-- ---------------------------------------------------------------------
-- Gatilhos de vaga
-- ---------------------------------------------------------------------
CREATE FUNCTION emp.tg_vaga_bu() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = emp, pg_temp AS $$
BEGIN
  IF NEW.id_empresa <> OLD.id_empresa THEN
    RAISE EXCEPTION 'EMP-RN01: a vaga nao pode trocar de empresa' USING ERRCODE = 'SC302';
  END IF;
  IF NEW.status <> OLD.status THEN
    IF NOT EXISTS (SELECT 1 FROM emp.transicao_vaga WHERE de = OLD.status AND para = NEW.status) THEN
      RAISE EXCEPTION 'EMP-RF05: transicao de vaga % -> % nao permitida', OLD.status, NEW.status
        USING ERRCODE = 'SC302';
    END IF;
    NEW.data_encerramento := CASE WHEN NEW.status IN ('ABERTA','SUSPENSA') THEN NULL ELSE CURRENT_DATE END;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_vaga_bu BEFORE UPDATE ON emp.vaga
  FOR EACH ROW EXECUTE FUNCTION emp.tg_vaga_bu();

-- Ao encerrar a vaga, as candidaturas ainda ativas sao recusadas (e isso vai para o historico).
CREATE FUNCTION emp.tg_vaga_au() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = emp, pg_temp AS $$
BEGIN
  IF NEW.status IN ('PREENCHIDA','ENCERRADA','CANCELADA') THEN
    PERFORM set_config('app.observacao', 'Vaga ' || lower(NEW.status), true);
    UPDATE emp.candidatura SET status = 'RECUSADA'
     WHERE id_vaga = NEW.id_vaga AND status IN ('ENVIADA','EM_ANALISE','ENTREVISTA','APROVADA');
    PERFORM set_config('app.observacao', '', true);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER tg_vaga_au AFTER UPDATE OF status ON emp.vaga
  FOR EACH ROW WHEN (NEW.status <> OLD.status) EXECUTE FUNCTION emp.tg_vaga_au();

-- Vaga nova so pode ser publicada por empresa ativa e sempre nasce ABERTA (EMP-UC02).
CREATE FUNCTION emp.tg_vaga_bi() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = emp, pg_temp AS $$
BEGIN
  IF (SELECT situacao FROM emp.empresa WHERE id_empresa = NEW.id_empresa) IS DISTINCT FROM 'ATIVA' THEN
    RAISE EXCEPTION 'EMP-UC01: somente empresa ativa publica vagas (empresa %)', NEW.id_empresa USING ERRCODE = 'SC301';
  END IF;
  NEW.status := 'ABERTA';
  NEW.data_encerramento := NULL;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_vaga_bi BEFORE INSERT ON emp.vaga
  FOR EACH ROW EXECUTE FUNCTION emp.tg_vaga_bi();

