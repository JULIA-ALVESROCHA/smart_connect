CREATE FUNCTION emp.fn_candidatar(p_id_candidato integer, p_id_vaga integer) RETURNS integer
LANGUAGE sql AS $$
  INSERT INTO emp.candidatura (id_candidato, id_vaga) VALUES (p_id_candidato, p_id_vaga)
  RETURNING id_candidatura
$$;

-- EMP-UC04
CREATE FUNCTION emp.fn_atualizar_candidatura(p_id_candidatura integer, p_novo_status text, p_observacao text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM set_config('app.observacao', coalesce(p_observacao, ''), true);
  UPDATE emp.candidatura SET status = p_novo_status WHERE id_candidatura = p_id_candidatura;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Candidatura % nao encontrada', p_id_candidatura USING ERRCODE = 'SC302';
  END IF;
  PERFORM set_config('app.observacao', '', true);
END $$;

-- EMP-RF07: vagas abertas, com area e empresa.
CREATE VIEW emp.vw_vagas_abertas AS
SELECT v.id_vaga, a.nome AS area, v.titulo, o.titulo AS ocupacao_cbo, e.id_empresa,
       coalesce(e.nome_fantasia, e.razao_social) AS empresa, b.nome AS bairro, v.tipo_contrato,
       v.salario, v.qtd_posicoes, esc.descricao AS escolaridade_minima, v.data_publicacao
  FROM emp.vaga v
  JOIN emp.area_profissional a USING (id_area)
  JOIN emp.empresa e USING (id_empresa)
  JOIN ref.cbo_ocupacao o USING (cod_cbo)
  JOIN ref.escolaridade esc ON esc.id_escolaridade = v.id_escolaridade_minima
  JOIN cid.logradouro l ON l.id_logradouro = e.id_logradouro
  JOIN cid.bairro b USING (id_bairro)
 WHERE v.status = 'ABERTA';

-- EMP-RF08: candidatos por empresa e vaga.
CREATE VIEW emp.vw_candidatos_por_vaga AS
SELECT e.id_empresa, coalesce(e.nome_fantasia, e.razao_social) AS empresa, v.id_vaga, v.titulo AS vaga, v.status AS status_vaga,
       ca.id_candidatura, c.id_candidato, cb.nome AS candidato, cb.idade, esc.descricao AS escolaridade,
       ca.status AS status_candidatura, ca.data_candidatura, ca.data_status
  FROM emp.candidatura ca
  JOIN emp.vaga v USING (id_vaga)
  JOIN emp.empresa e USING (id_empresa)
  JOIN emp.candidato c USING (id_candidato)
  JOIN cid.vw_cidadao_basico cb USING (id_cidadao)
  JOIN ref.escolaridade esc USING (id_escolaridade);
