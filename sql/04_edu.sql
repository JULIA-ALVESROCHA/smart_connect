CREATE TABLE edu.escola (
  id_escola     integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cod_inep      char(8)      NOT NULL UNIQUE CHECK (cod_inep ~ '^\d{8}$'),
  nome          varchar(120) NOT NULL UNIQUE,
  id_logradouro integer      NOT NULL REFERENCES cid.logradouro,
  numero        varchar(10)  NOT NULL,
  ano_inicial   smallint     NOT NULL CHECK (ano_inicial BETWEEN 1 AND 9),
  ano_final     smallint     NOT NULL CHECK (ano_final BETWEEN 1 AND 9),
  telefone      varchar(11),
  situacao      varchar(10)  NOT NULL DEFAULT 'ATIVA' CHECK (situacao IN ('ATIVA','PARALISADA','EXTINTA')),
  CONSTRAINT ck_escola_anos CHECK (ano_final >= ano_inicial)
);
COMMENT ON TABLE edu.escola IS 'Escolas da rede municipal (EDU-RF01). cod_inep segue o formato do codigo INEP de 8 digitos';
COMMENT ON COLUMN edu.escola.ano_inicial IS 'Primeiro ano escolar ofertado (1 a 9)';

-- Componente -> area do conhecimento e uma dependencia transitiva da disciplina; fica em tabelas proprias.
CREATE TABLE edu.area_conhecimento (
  id_area smallint    PRIMARY KEY,
  nome    varchar(40) NOT NULL UNIQUE
);
CREATE TABLE edu.componente_curricular (
  id_componente smallint    PRIMARY KEY,
  sigla         char(3)     NOT NULL UNIQUE,
  nome          varchar(40) NOT NULL UNIQUE,
  id_area       smallint    NOT NULL REFERENCES edu.area_conhecimento
);
COMMENT ON TABLE edu.componente_curricular IS 'Componentes curriculares do Ensino Fundamental conforme a BNCC';

CREATE TABLE edu.disciplina (
  id_disciplina  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo         varchar(10)  NOT NULL,
  nome           varchar(60)  NOT NULL,
  id_componente  smallint     NOT NULL REFERENCES edu.componente_curricular,
  ano_escolar    smallint     NOT NULL CHECK (ano_escolar BETWEEN 1 AND 9),
  carga_horaria  smallint     NOT NULL CHECK (carga_horaria > 0),
  CONSTRAINT uq_disciplina_codigo UNIQUE (codigo),                       -- EDU-RN04
  CONSTRAINT uq_disciplina_componente_ano UNIQUE (id_componente, ano_escolar)
);
COMMENT ON TABLE edu.disciplina IS 'Disciplina = componente curricular em um ano escolar. EDU-RN04: codigo unico';

CREATE TABLE edu.periodo_letivo (
  id_periodo  smallint    PRIMARY KEY,
  ano         smallint    NOT NULL UNIQUE CHECK (ano BETWEEN 2000 AND 2100),
  data_inicio date        NOT NULL,
  data_fim    date        NOT NULL,
  situacao    varchar(10) NOT NULL CHECK (situacao IN ('PLANEJADO','ABERTO','ENCERRADO')),
  CONSTRAINT ck_periodo_datas CHECK (data_fim > data_inicio)
);

CREATE TABLE edu.aluno (
  id_aluno      integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cidadao    integer     NOT NULL REFERENCES cid.cidadao,
  id_escola     integer     NOT NULL REFERENCES edu.escola,          -- EDU-RN01
  ra            char(10)    NOT NULL UNIQUE,
  ano_escolar   smallint    NOT NULL CHECK (ano_escolar BETWEEN 1 AND 9),
  turno         varchar(8)  NOT NULL CHECK (turno IN ('MANHA','TARDE','INTEGRAL')),
  data_ingresso date        NOT NULL,
  situacao      varchar(11) NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO','TRANSFERIDO','EVADIDO','CONCLUINTE')),
  CONSTRAINT uq_aluno_cidadao UNIQUE (id_cidadao)   -- um cidadao e aluno uma unica vez
);
COMMENT ON TABLE edu.aluno IS 'Papel de aluno de um cidadao. Dados pessoais ficam em cid.cidadao. EDU-RN01: id_escola obrigatorio';

CREATE TABLE edu.professor (
  id_professor       integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cidadao         integer     NOT NULL REFERENCES cid.cidadao,
  registro_funcional char(8)     NOT NULL UNIQUE,
  formacao           varchar(80) NOT NULL,
  titulacao          varchar(15) NOT NULL CHECK (titulacao IN ('GRADUACAO','ESPECIALIZACAO','MESTRADO','DOUTORADO')),
  data_admissao      date        NOT NULL,
  situacao           varchar(10) NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO','AFASTADO','DESLIGADO')),
  CONSTRAINT uq_professor_cidadao UNIQUE (id_cidadao)
);
COMMENT ON TABLE edu.professor IS 'Papel de professor de um cidadao (EDU-RF03)';

-- EDU-RF08, EDU-RN05: relacionamento N:N professor x disciplina, organizado por escola e periodo.
CREATE TABLE edu.atribuicao_docente (
  id_escola     integer  NOT NULL REFERENCES edu.escola,
  id_disciplina integer  NOT NULL REFERENCES edu.disciplina,
  id_periodo    smallint NOT NULL REFERENCES edu.periodo_letivo,
  id_professor  integer  NOT NULL REFERENCES edu.professor,
  PRIMARY KEY (id_escola, id_disciplina, id_periodo, id_professor)
);
COMMENT ON TABLE edu.atribuicao_docente IS 'Vinculo professor x disciplina por escola e periodo letivo (EDU-RN05)';

-- EDU-RF05, EDU-RN02, EDU-RN03: relacionamento N:N aluno x disciplina por periodo letivo.
CREATE TABLE edu.matricula (
  id_matricula   integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno       integer      NOT NULL REFERENCES edu.aluno,       -- EDU-RN02
  id_disciplina  integer      NOT NULL REFERENCES edu.disciplina,  -- EDU-RN02
  id_periodo     smallint     NOT NULL REFERENCES edu.periodo_letivo,
  data_matricula date         NOT NULL DEFAULT CURRENT_DATE,
  situacao       varchar(10)  NOT NULL DEFAULT 'CURSANDO' CHECK (situacao IN ('CURSANDO','APROVADO','REPROVADO','CANCELADA')),
  nota_final     numeric(4,2) CHECK (nota_final BETWEEN 0 AND 10),
  frequencia_pct numeric(5,2) CHECK (frequencia_pct BETWEEN 0 AND 100),
  -- EDU-RN03: sem matricula duplicada na mesma disciplina e periodo.
  CONSTRAINT uq_matricula UNIQUE (id_aluno, id_disciplina, id_periodo),
  CONSTRAINT ck_matricula_resultado CHECK (situacao NOT IN ('APROVADO','REPROVADO') OR nota_final IS NOT NULL)
);
COMMENT ON TABLE edu.matricula IS 'Matricula do aluno em disciplina por periodo letivo. EDU-RN03 via uq_matricula';

-- EDU-RNF03: integridade da matricula no momento do registro.
CREATE FUNCTION edu.tg_matricula_valida() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = edu, pg_temp AS $$
DECLARE v_sit_aluno text; v_ini smallint; v_fim smallint; v_sit_per text; v_ano smallint;
BEGIN
  SELECT a.situacao, e.ano_inicial, e.ano_final INTO v_sit_aluno, v_ini, v_fim
    FROM edu.aluno a JOIN edu.escola e USING (id_escola) WHERE a.id_aluno = NEW.id_aluno;
  SELECT situacao INTO v_sit_per FROM edu.periodo_letivo WHERE id_periodo = NEW.id_periodo;
  SELECT ano_escolar INTO v_ano FROM edu.disciplina WHERE id_disciplina = NEW.id_disciplina;

  IF v_sit_aluno IS DISTINCT FROM 'ATIVO' THEN
    RAISE EXCEPTION 'EDU-RNF03: aluno % nao esta ativo', NEW.id_aluno USING ERRCODE = 'SC201';
  END IF;
  IF v_sit_per IS DISTINCT FROM 'ABERTO' THEN
    RAISE EXCEPTION 'EDU-RNF03: periodo letivo % nao esta aberto para matriculas', NEW.id_periodo USING ERRCODE = 'SC201';
  END IF;
  IF v_ano NOT BETWEEN v_ini AND v_fim THEN
    RAISE EXCEPTION 'EDU-RNF03: a escola do aluno nao oferta o % ano', v_ano USING ERRCODE = 'SC201';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_matricula_bi BEFORE INSERT ON edu.matricula
  FOR EACH ROW EXECUTE FUNCTION edu.tg_matricula_valida();

-- EDU-UC03: matricula o aluno em uma disciplina (as restricoes fazem a verificacao de duplicidade).
CREATE FUNCTION edu.fn_matricular(p_id_aluno integer, p_codigo_disciplina text, p_ano_letivo integer)
RETURNS integer LANGUAGE sql AS $$
  INSERT INTO edu.matricula (id_aluno, id_disciplina, id_periodo)
  SELECT p_id_aluno, d.id_disciplina, p.id_periodo
    FROM edu.disciplina d, edu.periodo_letivo p
   WHERE d.codigo = p_codigo_disciplina AND p.ano = p_ano_letivo
  RETURNING id_matricula
$$;

-- EDU-RF06 / EDU-UC04: disciplinas de um aluno, por periodo.
CREATE VIEW edu.vw_matriculas_aluno AS
SELECT a.id_aluno, a.ra, cb.nome AS aluno, e.nome AS escola, p.ano AS ano_letivo,
       d.codigo AS cod_disciplina, d.nome AS disciplina, m.situacao, m.nota_final, m.frequencia_pct
  FROM edu.matricula m
  JOIN edu.aluno a USING (id_aluno)
  JOIN cid.vw_cidadao_basico cb USING (id_cidadao)
  JOIN edu.escola e USING (id_escola)
  JOIN edu.disciplina d USING (id_disciplina)
  JOIN edu.periodo_letivo p USING (id_periodo);

-- EDU-RF07: alunos de uma disciplina, com o professor atribuido na escola.
CREATE VIEW edu.vw_alunos_disciplina AS
SELECT d.codigo AS cod_disciplina, d.nome AS disciplina, p.ano AS ano_letivo, e.id_escola, e.nome AS escola,
       a.id_aluno, a.ra, cb.nome AS aluno, m.situacao,
       (SELECT string_agg(pb.nome, ', ' ORDER BY pb.nome)
          FROM edu.atribuicao_docente ad
          JOIN edu.professor pr USING (id_professor)
          JOIN cid.vw_cidadao_basico pb ON pb.id_cidadao = pr.id_cidadao
         WHERE ad.id_escola = a.id_escola AND ad.id_disciplina = m.id_disciplina AND ad.id_periodo = m.id_periodo) AS professores
  FROM edu.matricula m
  JOIN edu.aluno a USING (id_aluno)
  JOIN cid.vw_cidadao_basico cb USING (id_cidadao)
  JOIN edu.escola e USING (id_escola)
  JOIN edu.disciplina d USING (id_disciplina)
  JOIN edu.periodo_letivo p USING (id_periodo);
