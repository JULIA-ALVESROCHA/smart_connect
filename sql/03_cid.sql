-- Ponto em aberto 04 resolvido: "regiao" = regiao administrativa, que agrupa bairros.
CREATE TABLE cid.regiao (
  id_regiao smallint    PRIMARY KEY,
  nome      varchar(40) NOT NULL UNIQUE
);
COMMENT ON TABLE cid.regiao IS 'Regioes administrativas de Nova Esperanca Digital (base de ASS-RF08)';

CREATE TABLE cid.bairro (
  id_bairro smallint    PRIMARY KEY,
  nome      varchar(60) NOT NULL UNIQUE,
  id_regiao smallint    NOT NULL REFERENCES cid.regiao
);
COMMENT ON TABLE cid.bairro IS 'Os 20 bairros do municipio';

-- CEP -> (tipo, nome, bairro). Separar o logradouro evita repetir esses dados em cada
-- endereco de cidadao, escola, empresa e unidade (dependencia transitiva eliminada, 3FN).
CREATE TABLE cid.logradouro (
  id_logradouro integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cep           ref.cep      NOT NULL UNIQUE,
  tipo          varchar(15)  NOT NULL CHECK (tipo IN ('Rua','Avenida','Travessa','Alameda','Praça','Rodovia')),
  nome          varchar(100) NOT NULL,
  id_bairro     smallint     NOT NULL REFERENCES cid.bairro
);
COMMENT ON TABLE cid.logradouro IS 'Logradouros do municipio, um CEP por logradouro';

CREATE TABLE cid.cidadao (
  id_cidadao               integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cpf                      ref.cpf      NOT NULL,
  nome                     varchar(120) NOT NULL CHECK (length(btrim(nome)) >= 3),
  nome_social              varchar(120),
  data_nascimento          date         NOT NULL CHECK (data_nascimento >= DATE '1900-01-01' AND data_nascimento <= CURRENT_DATE),
  sexo                     char(1)      NOT NULL CHECK (sexo IN ('F','M','N')),
  nome_mae                 varchar(120) NOT NULL CHECK (length(btrim(nome_mae)) >= 3),
  cod_municipio_nascimento integer      REFERENCES ref.municipio,
  email                    varchar(254) CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  situacao                 varchar(10)  NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO','INATIVO','FALECIDO')),
  data_cadastro            timestamptz  NOT NULL DEFAULT now(),
  data_atualizacao         timestamptz  NOT NULL DEFAULT now(),
  -- CID-RN01: cadastro unico. O CPF e o criterio tecnico de unicidade (ponto em aberto 02).
  CONSTRAINT uq_cidadao_cpf UNIQUE (cpf)
);
COMMENT ON TABLE cid.cidadao IS 'Base cadastral unica. Os modulos EDU, EMP e ASS referenciam id_cidadao e nao replicam dados pessoais';
COMMENT ON COLUMN cid.cidadao.cpf IS 'CID-RN01: unico e com digitos verificadores validados';
COMMENT ON COLUMN cid.cidadao.nome_mae IS 'CID-RN02: compoe os dados minimos de identificacao (cpf, nome, nascimento, sexo, mae)';
COMMENT ON COLUMN cid.cidadao.sexo IS 'F, M ou N (nao informado)';

-- CID-RN03: 1 cidadao, N telefones. Atributo multivalorado vira tabela (1FN).
CREATE TABLE cid.telefone (
  id_telefone integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cidadao  integer     NOT NULL REFERENCES cid.cidadao ON DELETE CASCADE,
  ddd         char(2)     NOT NULL CHECK (ddd ~ '^[1-9]\d$'),
  numero      varchar(9)  NOT NULL CHECK (numero ~ '^\d{8,9}$'),
  tipo        varchar(8)  NOT NULL CHECK (tipo IN ('CELULAR','FIXO','RECADO')),
  principal   boolean     NOT NULL DEFAULT false,
  CONSTRAINT uq_telefone UNIQUE (id_cidadao, ddd, numero)
);
-- No maximo um telefone principal por cidadao.
CREATE UNIQUE INDEX uq_telefone_principal ON cid.telefone (id_cidadao) WHERE principal;

-- CID-RF05, CID-RF06, CID-RN04: endereco com vigencia. O vigente tem data_fim nula.
CREATE TABLE cid.endereco_cidadao (
  id_endereco   integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cidadao    integer     NOT NULL REFERENCES cid.cidadao,
  id_logradouro integer     NOT NULL REFERENCES cid.logradouro,
  numero        varchar(10) NOT NULL,
  complemento   varchar(40),
  data_inicio   date        NOT NULL,
  data_fim      date,
  CONSTRAINT ck_endereco_periodo CHECK (data_fim IS NULL OR data_fim >= data_inicio),
  -- Dois enderecos do mesmo cidadao nunca se sobrepoem no tempo.
  CONSTRAINT ex_endereco_sem_sobreposicao EXCLUDE USING gist (
    id_cidadao WITH =,
    daterange(data_inicio, coalesce(data_fim, 'infinity'::date), '[)') WITH &&
  )
);
-- Exatamente um endereco vigente por cidadao (no maximo um; a funcao de cadastro garante o primeiro).
CREATE UNIQUE INDEX uq_endereco_vigente ON cid.endereco_cidadao (id_cidadao) WHERE data_fim IS NULL;
COMMENT ON TABLE cid.endereco_cidadao IS 'Historico de enderecos. Linhas encerradas sao imutaveis (CID-RN04, GER-RNF04)';

-- ---------------------------------------------------------------------
-- Gatilhos
-- ---------------------------------------------------------------------
CREATE FUNCTION cid.tg_cidadao_atualizacao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.data_atualizacao := now();
  RETURN NEW;
END $$;
CREATE TRIGGER tg_cidadao_bu BEFORE UPDATE ON cid.cidadao
  FOR EACH ROW EXECUTE FUNCTION cid.tg_cidadao_atualizacao();

-- CID-RN04: historico nao destrutivo. Proibe DELETE e qualquer UPDATE que nao seja
-- o encerramento (preencher data_fim) do endereco vigente.
CREATE FUNCTION cid.tg_endereco_protege_historico() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'CID-RN04: historico de enderecos nao pode ser apagado (endereco %)', OLD.id_endereco
      USING ERRCODE = 'SC101';
  END IF;
  IF OLD.data_fim IS NOT NULL THEN
    RAISE EXCEPTION 'CID-RN04: endereco encerrado e imutavel (endereco %)', OLD.id_endereco
      USING ERRCODE = 'SC101';
  END IF;
  IF (NEW.id_cidadao, NEW.id_logradouro, NEW.numero, NEW.complemento, NEW.data_inicio)
     IS DISTINCT FROM (OLD.id_cidadao, OLD.id_logradouro, OLD.numero, OLD.complemento, OLD.data_inicio) THEN
    RAISE EXCEPTION 'CID-RN04: para mudar de endereco use cid.fn_alterar_endereco; o registro anterior e preservado'
      USING ERRCODE = 'SC101';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_endereco_bud BEFORE UPDATE OR DELETE ON cid.endereco_cidadao
  FOR EACH ROW EXECUTE FUNCTION cid.tg_endereco_protege_historico();

-- ---------------------------------------------------------------------
-- Operacoes dos casos de uso
-- ---------------------------------------------------------------------
-- CID-UC01: cadastra cidadao, endereco e telefone em uma unica transacao.
CREATE FUNCTION cid.fn_cadastrar_cidadao(
  p_cpf text, p_nome text, p_data_nascimento date, p_sexo text, p_nome_mae text,
  p_id_logradouro integer, p_numero text, p_complemento text DEFAULT NULL,
  p_ddd text DEFAULT NULL, p_telefone text DEFAULT NULL, p_cod_municipio_nascimento integer DEFAULT NULL
) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE v_id integer;
BEGIN
  INSERT INTO cid.cidadao (cpf, nome, data_nascimento, sexo, nome_mae, cod_municipio_nascimento)
  VALUES (p_cpf, btrim(p_nome), p_data_nascimento, p_sexo, btrim(p_nome_mae), p_cod_municipio_nascimento)
  RETURNING id_cidadao INTO v_id;

  INSERT INTO cid.endereco_cidadao (id_cidadao, id_logradouro, numero, complemento, data_inicio)
  VALUES (v_id, p_id_logradouro, p_numero, p_complemento, CURRENT_DATE);

  IF p_telefone IS NOT NULL THEN
    INSERT INTO cid.telefone (id_cidadao, ddd, numero, tipo, principal)
    VALUES (v_id, p_ddd, p_telefone, CASE WHEN length(p_telefone) = 9 THEN 'CELULAR' ELSE 'FIXO' END, true);
  END IF;
  RETURN v_id;
END $$;

-- CID-UC02: encerra o endereco vigente e registra o novo. Nada e sobrescrito.
CREATE FUNCTION cid.fn_alterar_endereco(
  p_id_cidadao integer, p_id_logradouro integer, p_numero text,
  p_complemento text DEFAULT NULL, p_data date DEFAULT CURRENT_DATE
) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE v_id integer;
BEGIN
  UPDATE cid.endereco_cidadao
     SET data_fim = p_data
   WHERE id_cidadao = p_id_cidadao AND data_fim IS NULL;

  INSERT INTO cid.endereco_cidadao (id_cidadao, id_logradouro, numero, complemento, data_inicio)
  VALUES (p_id_cidadao, p_id_logradouro, p_numero, p_complemento, p_data)
  RETURNING id_endereco INTO v_id;
  RETURN v_id;
END $$;

-- ---------------------------------------------------------------------
-- Visoes do modulo
-- ---------------------------------------------------------------------
CREATE VIEW cid.vw_endereco_vigente AS
SELECT e.id_cidadao, e.id_endereco, l.tipo || ' ' || l.nome AS logradouro, e.numero, e.complemento,
       l.cep, b.id_bairro, b.nome AS bairro, r.id_regiao, r.nome AS regiao, e.data_inicio
  FROM cid.endereco_cidadao e
  JOIN cid.logradouro l USING (id_logradouro)
  JOIN cid.bairro b USING (id_bairro)
  JOIN cid.regiao r USING (id_regiao)
 WHERE e.data_fim IS NULL;

-- Visao de dados minimos para os demais modulos: identifica a pessoa sem expor
-- CPF completo, filiacao, contato ou endereco (LGPD, CID-RNF02, GER-RNF05).
CREATE VIEW cid.vw_cidadao_basico AS
SELECT c.id_cidadao, coalesce(c.nome_social, c.nome) AS nome, ref.fn_mascarar_cpf(c.cpf) AS cpf_mascarado,
       c.data_nascimento, date_part('year', age(c.data_nascimento))::int AS idade, c.sexo, c.situacao
  FROM cid.cidadao c;

-- CID-RF07 e CID-UC03: pesquisa por CPF exato ou por trecho do nome (sem acento, sem caixa).
CREATE FUNCTION cid.fn_pesquisar_cidadao(p_termo text, p_limite integer DEFAULT 20)
RETURNS TABLE (id_cidadao integer, cpf text, nome text, data_nascimento date, nome_mae text, bairro text)
LANGUAGE plpgsql STABLE AS $$
DECLARE v_digitos text := regexp_replace(p_termo, '\D', '', 'g');
BEGIN
  IF length(v_digitos) = 11 AND p_termo !~ '[A-Za-z]' THEN
    RETURN QUERY
      SELECT c.id_cidadao, c.cpf::text, c.nome::text, c.data_nascimento, c.nome_mae::text, v.bairro::text
        FROM cid.cidadao c LEFT JOIN cid.vw_endereco_vigente v USING (id_cidadao)
       WHERE c.cpf = v_digitos;
  ELSE
    RETURN QUERY
      SELECT c.id_cidadao, c.cpf::text, c.nome::text, c.data_nascimento, c.nome_mae::text, v.bairro::text
        FROM cid.cidadao c LEFT JOIN cid.vw_endereco_vigente v USING (id_cidadao)
       WHERE ref.fn_normalizar(c.nome) LIKE '%' || ref.fn_normalizar(p_termo) || '%'
       ORDER BY similarity(ref.fn_normalizar(c.nome), ref.fn_normalizar(p_termo)) DESC, c.nome
       LIMIT p_limite;
  END IF;
END $$;

-- Localizacao por CPF para os outros modulos ("localiza o cidadao na base cadastral unica").
-- SECURITY DEFINER: devolve so o minimo, sem dar SELECT na tabela inteira.
CREATE FUNCTION cid.fn_localizar_cidadao(p_cpf text)
RETURNS TABLE (id_cidadao integer, nome text, data_nascimento date, situacao text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = cid, pg_temp AS $$
  SELECT c.id_cidadao, coalesce(c.nome_social, c.nome)::text, c.data_nascimento, c.situacao::text
    FROM cid.cidadao c
   WHERE c.cpf = regexp_replace(p_cpf, '\D', '', 'g')
$$;
