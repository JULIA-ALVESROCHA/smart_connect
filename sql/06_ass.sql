CREATE FUNCTION ass.fn_vincular_programa(p_id_beneficiario integer, p_codigo_programa text, p_valor numeric DEFAULT NULL)
RETURNS integer LANGUAGE sql AS $$
  INSERT INTO ass.beneficio_concedido (id_beneficiario, id_programa, valor_mensal)
  SELECT p_id_beneficiario, p.id_programa, coalesce(p_valor, p.valor_referencia, 0)
    FROM ass.programa p WHERE p.codigo = p_codigo_programa
  RETURNING id_beneficio
$$;

