  id_cidadao            integer     NOT NULL REFERENCES cid.cidadao,
  cargo                 varchar(20) NOT NULL CHECK (cargo IN ('ASSISTENTE_SOCIAL','PSICOLOGO','EDUCADOR_SOCIAL')),
  registro_profissional varchar(20),
