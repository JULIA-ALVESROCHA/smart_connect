-- Renda e composicao de cada familia ativa.
CREATE VIEW ass.vw_familia_resumo AS
SELECT f.id_familia, f.codigo_familiar, f.data_atualizacao,
       count(*) AS integrantes,
       sum(fm.renda_mensal) AS renda_total,
       round(sum(fm.renda_mensal) / count(*), 2) AS renda_per_capita,
       max(fm.id_cidadao) FILTER (WHERE fm.parentesco = 'RESPONSAVEL') AS id_cidadao_responsavel
  FROM ass.familia f
  JOIN ass.familia_membro fm USING (id_familia)
 WHERE fm.data_saida IS NULL AND f.situacao = 'ATIVA'
 GROUP BY f.id_familia;

-- ASS-RF06: historico de atendimentos de um beneficiario.
CREATE VIEW ass.vw_historico_atendimentos AS
SELECT a.id_beneficiario, cb.nome AS beneficiario, a.id_atendimento, a.data_hora, t.nome AS tipo,
       u.nome AS unidade, pc.nome AS profissional, p.nome AS programa, a.descricao, a.encaminhamento
  FROM ass.atendimento a
  JOIN ass.beneficiario b USING (id_beneficiario)
  JOIN cid.vw_cidadao_basico cb ON cb.id_cidadao = b.id_cidadao
  JOIN ass.tipo_atendimento t USING (id_tipo)
  JOIN ass.unidade_atendimento u USING (id_unidade)
  JOIN ass.profissional pr USING (id_profissional)
  JOIN cid.vw_cidadao_basico pc ON pc.id_cidadao = pr.id_cidadao
  LEFT JOIN ass.programa p ON p.id_programa = a.id_programa;
