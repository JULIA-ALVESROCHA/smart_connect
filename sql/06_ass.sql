CREATE TABLE ass.familia (
  id_familia        integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_familiar   char(11)    NOT NULL UNIQUE CHECK (codigo_familiar ~ '^\d{11}$'),
  data_cadastro     date        NOT NULL DEFAULT CURRENT_DATE,
  data_atualizacao  date        NOT NULL DEFAULT CURRENT_DATE,
  situacao          varchar(8)  NOT NULL DEFAULT 'ATIVA' CHECK (situacao IN ('ATIVA','INATIVA')),
  CONSTRAINT ck_familia_datas CHECK (data_atualizacao >= data_cadastro)
);
COMMENT ON TABLE ass.familia IS 'Nucleo familiar (ASS-RF01). O endereco da familia e o endereco vigente do responsavel em cid';

-- ASS-UC01: integrantes vem da base cadastral unica (ASS-RN01).
CREATE TABLE ass.familia_membro (
  id_familia   integer       NOT NULL REFERENCES ass.familia,
  id_cidadao   integer       NOT NULL REFERENCES cid.cidadao,
  data_entrada date          NOT NULL DEFAULT CURRENT_DATE,
  data_saida   date,
  parentesco   varchar(12)   NOT NULL CHECK (parentesco IN ('RESPONSAVEL','CONJUGE','FILHO','PAI_MAE','NETO','OUTRO')),
  renda_mensal numeric(10,2) NOT NULL DEFAULT 0 CHECK (renda_mensal >= 0),
  PRIMARY KEY (id_familia, id_cidadao, data_entrada),
  CONSTRAINT ck_membro_datas CHECK (data_saida IS NULL OR data_saida >= data_entrada)
);
-- Um cidadao integra no maximo uma familia por vez.
CREATE UNIQUE INDEX uq_membro_familia_atual ON ass.familia_membro (id_cidadao) WHERE data_saida IS NULL;
-- Cada familia tem no maximo um responsavel familiar por vez.
CREATE UNIQUE INDEX uq_familia_responsavel ON ass.familia_membro (id_familia)
  WHERE parentesco = 'RESPONSAVEL' AND data_saida IS NULL;
COMMENT ON TABLE ass.familia_membro IS 'Composicao familiar com vigencia. renda_mensal = renda declarada do integrante neste cadastro familiar';

CREATE TABLE ass.beneficiario (
  id_beneficiario integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cidadao      integer     NOT NULL REFERENCES cid.cidadao,     -- ASS-RN01
  nis             char(11)    NOT NULL UNIQUE CHECK (nis ~ '^\d{11}$'),
  pcd             boolean     NOT NULL DEFAULT false,
  data_cadastro   date        NOT NULL DEFAULT CURRENT_DATE,
  situacao        varchar(8)  NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO','INATIVO')),
  CONSTRAINT uq_beneficiario_cidadao UNIQUE (id_cidadao)
);
COMMENT ON TABLE ass.beneficiario IS 'Papel de beneficiario de um cidadao (ASS-RF02). ASS-RN01: FK obrigatoria para cid.cidadao';
COMMENT ON COLUMN ass.beneficiario.pcd IS 'Pessoa com deficiencia. Dado pessoal sensivel (LGPD art. 5, II): acesso restrito ao perfil de assistencia';

CREATE TABLE ass.programa (
  id_programa      smallint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo           varchar(12)   NOT NULL UNIQUE,
  nome             varchar(80)   NOT NULL UNIQUE,
  esfera           varchar(9)    NOT NULL CHECK (esfera IN ('FEDERAL','ESTADUAL','MUNICIPAL')),
  base_legal       varchar(120),
  valor_referencia numeric(10,2) CHECK (valor_referencia >= 0),
  data_inicio      date          NOT NULL,
  data_fim         date,
  ativo            boolean       NOT NULL DEFAULT true,
  CONSTRAINT ck_programa_datas CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- ASS-RN02: criterios como dados. Um programa novo se cadastra sem alterar codigo.
CREATE TABLE ass.tipo_criterio (
  codigo    varchar(24)  PRIMARY KEY,
  descricao varchar(160) NOT NULL,
  usa_valor boolean      NOT NULL
);
INSERT INTO ass.tipo_criterio VALUES
 ('RENDA_PER_CAPITA_MAX','Renda familiar mensal por pessoa menor ou igual ao valor (R$)',true),
 ('IDADE_MIN','Idade do beneficiário maior ou igual ao valor (anos)',true),
 ('IDADE_MAX','Idade do beneficiário menor ou igual ao valor (anos)',true),
 ('PCD','Beneficiário é pessoa com deficiência',false),
 ('FREQUENCIA_ESCOLAR','Todo integrante da família de 7 a 14 anos é aluno ativo da rede municipal (integração com EDU)',false),
 ('POSSUI_ALUNO','A família tem ao menos um aluno ativo na rede municipal (integração com EDU)',false),
 ('CADASTRO_EMPREGO','Beneficiário é candidato ativo no módulo de emprego (integração com EMP)',false);

CREATE TABLE ass.criterio_elegibilidade (
  id_programa   smallint      NOT NULL REFERENCES ass.programa ON DELETE CASCADE,
  tipo_criterio varchar(24)   NOT NULL REFERENCES ass.tipo_criterio,
  valor         numeric(10,2),
  PRIMARY KEY (id_programa, tipo_criterio)
);
COMMENT ON TABLE ass.criterio_elegibilidade IS 'Criterios de cada programa (ASS-RN02). Todos precisam ser atendidos (conjuncao)';

-- ASS-RF04: vinculo beneficiario x programa ("beneficios concedidos").
CREATE TABLE ass.beneficio_concedido (
  id_beneficio        integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_beneficiario     integer       NOT NULL REFERENCES ass.beneficiario,
  id_programa         smallint      NOT NULL REFERENCES ass.programa,
  data_concessao      date          NOT NULL DEFAULT CURRENT_DATE,
  data_encerramento   date,
  situacao            varchar(9)    NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO','SUSPENSO','ENCERRADO')),
  valor_mensal        numeric(10,2) NOT NULL CHECK (valor_mensal >= 0),
  motivo_encerramento varchar(120),
  CONSTRAINT ck_beneficio_datas CHECK (data_encerramento IS NULL OR data_encerramento >= data_concessao),
  CONSTRAINT ck_beneficio_encerramento CHECK ((situacao = 'ENCERRADO') = (data_encerramento IS NOT NULL))
);
-- Sem dois vinculos em aberto do mesmo beneficiario no mesmo programa (ASS-RNF04).
CREATE UNIQUE INDEX uq_beneficio_em_aberto ON ass.beneficio_concedido (id_beneficiario, id_programa)
  WHERE situacao <> 'ENCERRADO';

