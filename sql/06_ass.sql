CREATE TABLE ass.atendimento (
  id_atendimento  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_beneficiario integer     NOT NULL REFERENCES ass.beneficiario,   -- ASS-RN03
