-- ASS-RN04: so beneficiario elegivel entra no programa.
CREATE FUNCTION ass.tg_beneficio_bi() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ass, pg_temp AS $$
DECLARE v_motivos text;
BEGIN
  IF NOT coalesce((SELECT ativo FROM ass.programa WHERE id_programa = NEW.id_programa), false) THEN
    RAISE EXCEPTION 'ASS-RNF04: programa % inexistente ou inativo', NEW.id_programa USING ERRCODE = 'SC401';
  END IF;
  IF (SELECT situacao FROM ass.beneficiario WHERE id_beneficiario = NEW.id_beneficiario) IS DISTINCT FROM 'ATIVO' THEN
    RAISE EXCEPTION 'ASS-RN04: beneficiario % inexistente ou inativo', NEW.id_beneficiario USING ERRCODE = 'SC401';
  END IF;
  IF NOT ass.fn_elegivel(NEW.id_beneficiario, NEW.id_programa, NEW.data_concessao) THEN
    SELECT string_agg(tipo_criterio || ' (exigido ' || exigido || ', apurado ' || apurado || ')', '; ')
      INTO v_motivos
      FROM ass.fn_avaliar_elegibilidade(NEW.id_beneficiario, NEW.id_programa, NEW.data_concessao)
     WHERE NOT atende;
    RAISE EXCEPTION 'ASS-RN04: beneficiario % nao e elegivel ao programa %: %',
      NEW.id_beneficiario, NEW.id_programa, coalesce(v_motivos, 'programa sem criterios')
      USING ERRCODE = 'SC401';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_beneficio_bi BEFORE INSERT ON ass.beneficio_concedido
  FOR EACH ROW EXECUTE FUNCTION ass.tg_beneficio_bi();

-- ASS-RN05, ASS-RNF03: atendimento e somente insercao.
CREATE FUNCTION ass.tg_atendimento_imutavel() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'ASS-RN05: atendimento registrado nao pode ser alterado nem apagado; registre um novo atendimento'
    USING ERRCODE = 'SC402';
END $$;
CREATE TRIGGER tg_atendimento_bud BEFORE UPDATE OR DELETE ON ass.atendimento
  FOR EACH ROW EXECUTE FUNCTION ass.tg_atendimento_imutavel();

-- ASS-RN02: todo programa tem ao menos um criterio. Gatilho de restricao adiado para o COMMIT,
-- o que permite inserir programa e criterios na mesma transacao.
CREATE FUNCTION ass.tg_programa_exige_criterio() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_id smallint;
BEGIN
  IF TG_OP = 'DELETE' THEN v_id := OLD.id_programa; ELSE v_id := NEW.id_programa; END IF;
  IF EXISTS (SELECT 1 FROM ass.programa WHERE id_programa = v_id)
     AND NOT EXISTS (SELECT 1 FROM ass.criterio_elegibilidade WHERE id_programa = v_id) THEN
    RAISE EXCEPTION 'ASS-RN02: o programa % precisa de ao menos um criterio de elegibilidade', v_id
      USING ERRCODE = 'SC403';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER tg_programa_criterio AFTER INSERT ON ass.programa
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ass.tg_programa_exige_criterio();
CREATE CONSTRAINT TRIGGER tg_criterio_minimo AFTER DELETE ON ass.criterio_elegibilidade
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ass.tg_programa_exige_criterio();

-- Criterio com valor quando o tipo exige valor.
CREATE FUNCTION ass.tg_criterio_valor() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT usa_valor FROM ass.tipo_criterio WHERE codigo = NEW.tipo_criterio) THEN
    IF NEW.valor IS NULL THEN
      RAISE EXCEPTION 'ASS-RN02: o criterio % exige valor', NEW.tipo_criterio USING ERRCODE = 'SC403';
    END IF;
  ELSE
    NEW.valor := NULL;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tg_criterio_biu BEFORE INSERT OR UPDATE ON ass.criterio_elegibilidade
  FOR EACH ROW EXECUTE FUNCTION ass.tg_criterio_valor();

