CREATE FUNCTION ass.fn_registrar_atendimento(
  p_id_beneficiario integer, p_id_profissional integer, p_id_unidade integer, p_id_tipo integer,
  p_descricao text, p_encaminhamento text DEFAULT NULL, p_id_programa integer DEFAULT NULL
) RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO ass.atendimento (id_beneficiario, id_profissional, id_unidade, id_tipo, id_programa, descricao, encaminhamento)
  VALUES (p_id_beneficiario, p_id_profissional, p_id_unidade, p_id_tipo, p_id_programa, p_descricao, p_encaminhamento)
  RETURNING id_atendimento
$$;

