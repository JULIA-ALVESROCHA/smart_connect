  CONSTRAINT ck_atendimento_data CHECK (data_hora <= now() + interval '1 day')
);
COMMENT ON TABLE ass.atendimento IS 'Historico de atendimentos. ASS-RN05: linhas nunca sao alteradas ou apagadas';

-- ---------------------------------------------------------------------
-- Elegibilidade (ASS-RN04). Uma linha por criterio do programa, com o valor apurado.
-- SECURITY DEFINER: o tecnico de assistencia obtem a resposta sem precisar de acesso
-- direto as tabelas de educacao e emprego.
-- ---------------------------------------------------------------------
CREATE FUNCTION ass.fn_avaliar_elegibilidade(p_id_beneficiario integer, p_id_programa integer, p_data date DEFAULT CURRENT_DATE)
RETURNS TABLE (tipo_criterio varchar, exigido text, apurado text, atende boolean)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ass, cid, edu, emp, pg_temp AS $$
  WITH b AS (
    SELECT b.id_beneficiario, b.id_cidadao, b.pcd,
           date_part('year', age(p_data, c.data_nascimento))::int AS idade
      FROM ass.beneficiario b JOIN cid.cidadao c USING (id_cidadao)
     WHERE b.id_beneficiario = p_id_beneficiario
  ), fam AS (
    SELECT fm.id_familia FROM ass.familia_membro fm JOIN b USING (id_cidadao) WHERE fm.data_saida IS NULL
  ), membros AS (
    SELECT fm.id_cidadao, fm.renda_mensal,
           date_part('year', age(p_data, c.data_nascimento))::int AS idade,
           EXISTS (SELECT 1 FROM edu.aluno a WHERE a.id_cidadao = fm.id_cidadao AND a.situacao = 'ATIVO') AS aluno_ativo
      FROM ass.familia_membro fm JOIN fam USING (id_familia) JOIN cid.cidadao c USING (id_cidadao)
     WHERE fm.data_saida IS NULL
  ), agg AS (
    SELECT count(*) AS n,
           round(sum(renda_mensal) / nullif(count(*), 0), 2) AS per_capita,
           count(*) FILTER (WHERE idade BETWEEN 7 AND 14) AS em_idade_escolar,
           count(*) FILTER (WHERE idade BETWEEN 7 AND 14 AND aluno_ativo) AS em_idade_escolar_na_escola,
           count(*) FILTER (WHERE aluno_ativo) AS alunos
      FROM membros
  )
  SELECT ce.tipo_criterio,
         CASE WHEN tc.usa_valor THEN ce.valor::text ELSE 'sim' END,
         CASE ce.tipo_criterio
           WHEN 'RENDA_PER_CAPITA_MAX' THEN coalesce(agg.per_capita::text, 'sem família')
           WHEN 'IDADE_MIN' THEN b.idade::text
           WHEN 'IDADE_MAX' THEN b.idade::text
           WHEN 'PCD' THEN CASE WHEN b.pcd THEN 'sim' ELSE 'não' END
           WHEN 'FREQUENCIA_ESCOLAR' THEN agg.em_idade_escolar_na_escola || ' de ' || agg.em_idade_escolar || ' na escola'
           WHEN 'POSSUI_ALUNO' THEN agg.alunos || ' aluno(s)'
           WHEN 'CADASTRO_EMPREGO' THEN CASE WHEN cand.ok THEN 'sim' ELSE 'não' END
         END,
         coalesce(CASE ce.tipo_criterio
           WHEN 'RENDA_PER_CAPITA_MAX' THEN agg.per_capita <= ce.valor
           WHEN 'IDADE_MIN' THEN b.idade >= ce.valor
           WHEN 'IDADE_MAX' THEN b.idade <= ce.valor
           WHEN 'PCD' THEN b.pcd
           WHEN 'FREQUENCIA_ESCOLAR' THEN agg.n > 0 AND agg.em_idade_escolar_na_escola = agg.em_idade_escolar
           WHEN 'POSSUI_ALUNO' THEN agg.alunos > 0
           WHEN 'CADASTRO_EMPREGO' THEN cand.ok
         END, false)
    FROM ass.criterio_elegibilidade ce
    JOIN ass.tipo_criterio tc ON tc.codigo = ce.tipo_criterio
    CROSS JOIN b
    CROSS JOIN agg
    CROSS JOIN LATERAL (SELECT EXISTS (SELECT 1 FROM emp.candidato k
                                        WHERE k.id_cidadao = b.id_cidadao AND k.situacao = 'ATIVO') AS ok) cand
   WHERE ce.id_programa = p_id_programa
$$;

CREATE FUNCTION ass.fn_elegivel(p_id_beneficiario integer, p_id_programa integer, p_data date DEFAULT CURRENT_DATE)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT coalesce(bool_and(atende), false)   -- sem criterios ou sem beneficiario = nao elegivel
    FROM ass.fn_avaliar_elegibilidade(p_id_beneficiario, p_id_programa, p_data)
$$;

